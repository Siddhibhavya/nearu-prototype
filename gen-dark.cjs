// Generates src/dark.css from the light stylesheets. Re-run after editing the light CSS:  node gen-dark.cjs
// Dark theme = a warm brown page with cream-beige cards. Text colours are written with CSS variables so a card can flip them back to dark ink.
// The student ID card is never touched: it keeps its light design in both modes.
const fs = require('fs');
const files = ['src/index.css', 'src/more.css', 'src/more2.css', 'src/more3.css', 'src/more4.css', 'src/more5.css', 'src/more6.css', 'src/more7.css', 'src/more8.css', 'src/more9.css', 'src/more10.css', 'src/more11.css', 'src/more12.css'];
const INK = '#f6efdc';
const PAPER = '#2b2119', HEAD = '#3a2a1a', CARD = '#f3e8d3', SURFACE = '#3a2d23';
const SKIP = /\.id-(card|photo|body|logo|name|title|rule|chip|stripes|bars|seal|no|tag|line)\b|\.(wishlist-checkbox|cart-check|co-check|nx-qty|mini-toggle|pd-qty)\b/;
const pageMap = [[/#faf5e4/gi, PAPER], [/#fff4ee/gi, PAPER], [/#fff5ce/gi, HEAD], [/rgba\(250,\s*245,\s*228,/gi, 'rgba(43,33,25,'], [/rgba\(255,\s*244,\s*238,/gi, 'rgba(43,33,25,']];
const accentBg = /(var\(--yellow\)|#fec12d|#ff5a5f|#fc5956|var\(--blue\)|#0e59d3|#0057e7|#2f9e44|#d6383e)/i;
const bgProps = /^(background(-color)?|background-image)$/;
const pureWhite = /^(white|#fff|#ffffff)$/i;
const out = [], cards = new Set();
const addRule = (sel, decls) => {
  if (SKIP.test(sel)) return;
  const next = [];
  const hasAccent = decls.some(([p, v]) => bgProps.test(p) && accentBg.test(v));
  const selectors = sel.split(',').map((s) => s.trim());
  for (const [p, v0] of decls) {
    if (bgProps.test(p)) {
      if (accentBg.test(v0)) continue;
      if (pureWhite.test(v0.trim())) {
        if (selectors.some((s) => /^\.(account-flow|onboarding-view|confirmed-view|nx-process|nx-done|so-view)$/.test(s))) { next.push([p, PAPER]); continue; }
        selectors.forEach((s) => { if (!/:|::/.test(s)) cards.add(s); }); continue;
      }
      let nv = v0; for (const [re, to] of pageMap) nv = nv.replace(re, to);
      if (nv !== v0) next.push([p, nv]);
    } else if (p === 'color') {
      if (hasAccent) { if (/var\(--ink\)|#17120e/i.test(v0)) next.push([p, '#17120e']); continue; }
      if (/var\(--ink\)|#17120e|#000\b|black/i.test(v0)) next.push([p, 'var(--ink)']);
      else if (/var\(--muted\)|#4f463d/i.test(v0)) next.push([p, 'var(--muted)']);
      else if (/var\(--blue\)|#0057e7|#0e59d3/i.test(v0)) next.push([p, 'var(--blue-text)']);
      else if (/rgba\(79,\s*70,\s*61/i.test(v0)) next.push([p, v0.replace(/rgba\(79,\s*70,\s*61/i, 'rgba(var(--muted-rgb)')]);
      else if (/rgba\(23,\s*18,\s*14/i.test(v0)) next.push([p, v0.replace(/rgba\(23,\s*18,\s*14/i, 'rgba(var(--ink-rgb)')]);
    } else if (/^border/.test(p)) {
      let nv = v0.replace(/var\(--ink\)|#17120e/gi, 'rgba(var(--ink-rgb),.55)').replace(/rgba\(23,\s*18,\s*14,\s*([\d.]+)\)/gi, 'rgba(var(--ink-rgb),$1)').replace(/#e8d9ae|var\(--line\)/gi, 'var(--line)');
      for (const [re, to] of pageMap) nv = nv.replace(re, to);
      if (nv !== v0) next.push([p, nv]);
    }
  }
  if (next.length) out.push(selectors.map((s) => '.phone-app.dark ' + s).join(', ') + ' { ' + next.map(([p, v]) => p + ': ' + v + ';').join(' ') + ' }');
};
for (const file of files) {
  let css = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/@import[^;]*;/g, '');
  let i = 0;
  const parse = (inner) => {
    while (i < css.length) {
      const open = css.indexOf('{', i), close = css.indexOf('}', i);
      if (open === -1 && close === -1) return;
      if (close !== -1 && (open === -1 || close < open)) { i = close + 1; if (inner) return; continue; }
      const sel = css.slice(i, open).trim();
      if (sel.startsWith('@media') || sel.startsWith('@supports')) { i = open + 1; parse(true); continue; }
      if (sel.startsWith('@')) { let d = 1, j = open + 1; while (d && j < css.length) { if (css[j] === '{') d++; else if (css[j] === '}') d--; j++; } i = j; continue; }
      const end = css.indexOf('}', open);
      const body = css.slice(open + 1, end);
      i = end + 1;
      if (/^(html|body|:root|\*)/.test(sel) || sel.includes('@')) continue;
      const decls = body.split(';').map((d) => d.trim()).filter(Boolean).map((d) => { const k = d.indexOf(':'); return [d.slice(0, k).trim(), d.slice(k + 1).trim().replace(/\s*!important/, '')]; });
      addRule(sel, decls);
    }
  };
  parse(false);
}
const cardScope = '--ink: #17120e; --ink-rgb: 23,18,14; --muted: #3a322b; --muted-rgb: 58,50,43; --blue-text: #0057e7; --line: #e8d9ae; color: #17120e;';
const head = `/* Dark theme, generated by gen-dark.cjs: warm brown page, cream-beige cards, lighter blue text on the page. The ID card is never restyled. */
.phone-app.dark { --ink: ${INK}; --ink-rgb: 246,239,220; --paper: ${PAPER}; --muted: #cfc3a8; --muted-rgb: 207,195,168; --blue: #4a8cff; --blue-text: #8db8ff; --line: #3a3027; background: ${PAPER}; color: ${INK}; color-scheme: dark; box-shadow: none; }
.phone-app.dark .id-card { ${cardScope} }
.phone-app.dark .brand-logo, .phone-app.dark .drawer-watermark { filter: invert(1) brightness(1.1); }
.phone-app.dark .status-bar { color: #fff; }
.phone-app.dark .status-network > img { filter: brightness(0) invert(1); }
.phone-app.dark .app-header { background: ${HEAD} !important; }
.phone-app.dark .search-pill { background: ${CARD}; border-color: transparent; }
.phone-app.dark .search-pill input { background: transparent; color: #17120e; }
.phone-app.dark .search-pill input::placeholder { color: #7a6e60; }
.phone-app.dark .search-pill img { filter: none; opacity: .7; }
.phone-app.dark .menu-button span { background: ${INK}; }
.phone-app.dark .bell-dot { border-color: ${PAPER}; }
.phone-app.dark .order-action, .phone-app.dark .payment-action { color: #17120e !important; }
.phone-app.dark input, .phone-app.dark textarea, .phone-app.dark select { color: inherit; }
.phone-app.dark ::placeholder { color: #a99d85; opacity: 1; }
.phone-app.dark .mobile-nav .nav-item.selected, .phone-app.dark .mobile-nav .selected:hover { background: transparent !important; color: #f6efdc !important; }
.phone-app.dark .mobile-nav .selected img, .phone-app.dark .mobile-nav .selected:hover img { filter: brightness(0) invert(1) !important; }
.phone-app.dark .mobile-nav::before, .phone-app.dark .mobile-nav.buyer-nav::before, .phone-app.dark .mobile-nav.seller-nav::before { background: rgba(43,33,25,.97) !important; }
.phone-app.dark .drawer-links button.active, .phone-app.dark .drawer-links button.active:hover { color: #17120e; }
.phone-app.dark .drawer-links .active .drawer-icon { color: #17120e; }
.phone-app.dark .side-menu { background: ${PAPER}; }
.phone-app.dark .page-bar { background: ${PAPER}; }
`;
const cardRule = `.phone-app.dark :is(${[...cards].join(', ')}) { background: ${CARD}; border-color: transparent; ${cardScope} }\n.phone-app.dark :is(${[...cards].join(', ')}) :is(button, input, textarea) { color: inherit; }\n`;
fs.writeFileSync('src/dark.css', head + cardRule + out.join('\n') + '\n');
console.log('dark.css rules:', out.length, 'card selectors:', cards.size);
